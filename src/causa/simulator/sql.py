def import_stmt(table: str, columns: list[str], file_name: str) -> str:
    """The statement a connector would issue for a bulk load; recorded in the query log."""
    cols = ", ".join(c.upper() for c in columns)
    return f"IMPORT INTO {table} ({cols}) FROM LOCAL CSV FILE '{file_name}' COLUMN SEPARATOR = ','"


def stg_orders(lo: datetime, hi: datetime) -> str:
    return f"""INSERT INTO STG.ORDERS
SELECT o.ORDER_ID, o.CUSTOMER_ID, CAST(o.ORDER_TS AS DATE), o.ORDER_TS, o.CHANNEL, o.CURRENCY,
       fx.RATE_TO_EUR, o.SOURCE_FEED, o.LOADED_AT
FROM RAW.SHOP_ORDERS o
JOIN RAW.FX_RATES fx ON fx.RATE_DATE = CAST(o.ORDER_TS AS DATE) AND fx.CURRENCY = o.CURRENCY
WHERE o.LOADED_AT >= {ts(lo)} AND o.LOADED_AT < {ts(hi)}
  AND o.ORDER_TS IS NOT NULL
  AND o.ORDER_STATUS <> 'CANCELLED'"""


def stg_order_lines(lo: datetime, hi: datetime) -> str:
    return f"""INSERT INTO STG.ORDER_LINES
SELECT l.ORDER_ID, l.LINE_NO, l.PRODUCT_ID, l.QUANTITY, l.UNIT_PRICE, l.DISCOUNT_PCT,
       l.SOURCE_FEED, l.LOADED_AT
FROM RAW.SHOP_ORDER_LINES l
WHERE l.LOADED_AT >= {ts(lo)} AND l.LOADED_AT < {ts(hi)}"""


def fct_order_lines(lo: datetime, hi: datetime) -> str:
    amount = "CAST(l.QUANTITY AS DOUBLE) * l.UNIT_PRICE * o.FX_RATE_TO_EUR"
    return f"""INSERT INTO MART.FCT_ORDER_LINES
SELECT o.ORDER_DATE, o.ORDER_ID, l.LINE_NO, o.CUSTOMER_ID, c.CUSTOMER_NAME, c.SEGMENT, c.REGION,
       c.COUNTRY, o.CHANNEL, l.PRODUCT_ID, p.CATEGORY, l.QUANTITY,
       {amount} AS GROSS_REVENUE_EUR,
       {amount} * l.DISCOUNT_PCT / 100 AS DISCOUNT_EUR,
       {amount} * (1 - l.DISCOUNT_PCT / 100) AS NET_REVENUE_EUR,
       l.LOADED_AT
FROM STG.ORDER_LINES l
JOIN STG.ORDERS o ON o.ORDER_ID = l.ORDER_ID
JOIN RAW.ERP_PRODUCTS p ON p.PRODUCT_ID = l.PRODUCT_ID
JOIN RAW.CRM_CUSTOMERS c ON c.CUSTOMER_ID = o.CUSTOMER_ID
WHERE l.LOADED_AT >= {ts(lo)} AND l.LOADED_AT < {ts(hi)}"""


